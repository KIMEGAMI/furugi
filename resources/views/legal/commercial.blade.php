    <h2>販売サービス</h2>
    <p>古着販売向け在庫管理システム FURUGI Premiumプラン</p>
    <p>商品登録数の上限拡張、CSV取込、CSV出力、売上分析、ジャンル別分析など、販売管理を支援する機能を提供します。</p>

    <h2>販売価格</h2>
    <p>Premiumプランは月額480円を想定しています。</p>
    <p>実際の表示価格は、決済画面に表示される金額をご確認ください。キャンペーンや設定変更により、表示価格が変更される場合があります。</p>

    <h2>支払方法</h2>
    <p>外部決済サービスが対応するクレジットカード決済その他の方法を利用できます。</p>
    <p>支払方法の詳細、利用可能なカードブランド、請求タイミングは、決済画面の表示に従います。</p>

    <h2>サービス提供時期</h2>
    <p>決済完了後、Premium機能が有効化されます。</p>
    <p>通信状況、決済処理状況、外部サービスの反映状況により、有効化まで時間がかかる場合があります。</p>

    <h2>解約</h2>
    <p>利用者は、アカウント画面または決済ポータルからPremiumプランを解約できます。</p>
    <p>解約後の利用可能期間は、決済サービスの請求周期に従います。解約操作後も、期間終了まではPremium機能を利用できる場合があります。</p>

    <h2>返金</h2>
    <p>サービスの性質上、利用開始後の返金は原則として行いません。</p>
    <p>ただし、法令上必要な場合、または当サービスが個別に返金を認める場合はこの限りではありません。</p>

