    <h2>1. 取得する情報</h2>
    <p>当サービスは、アカウント登録時のメールアドレス、ログイン認証に必要な情報、商品情報、商品画像、売上管理に必要な情報を取得します。</p>
    <p>お問い合わせをいただく場合は、お名前、メールアドレス、件名、お問い合わせ内容を取得します。</p>

    <h2>2. 利用目的</h2>
    <p>取得した情報は、サービス提供、本人確認、プラン管理、問い合わせ対応、不正利用防止、障害調査、機能改善のために利用します。</p>
    <p>利用者の同意なく、目的外の利用を行わないよう努めます。</p>

    <h2>3. 決済情報の取り扱い</h2>
    <p>Premiumプランの決済は、外部決済サービスを通じて処理されます。</p>
    <p>当サービスは、クレジットカード番号などの機微な決済情報を直接保存しません。決済に関する詳細は、外部決済サービスの画面や規約をご確認ください。</p>

    <h2>4. 第三者提供</h2>
    <p>法令に基づく場合、利用者の同意がある場合、またはサービス提供に必要な委託先に限定して取り扱う場合を除き、個人情報を第三者に提供しません。</p>
    <p>委託先を利用する場合も、必要な範囲に限定して情報を取り扱います。</p>

    <h2>5. 安全管理</h2>
    <p>当サービスは、不正アクセス、漏えい、改ざん、滅失を防ぐため、必要かつ適切な安全管理措置を講じます。</p>
    <p>パスワードやAPIキーなどの機密情報を、お問い合わせフォームに入力しないでください。</p>

    <h2>6. データ削除</h2>
    <p>アカウント削除時には、関連する登録データや商品画像を削除する設計としています。</p>
    <p>ただし、法令対応、不正利用調査、決済記録の確認などのために必要な情報は、一定期間保持する場合があります。</p>

    <h2>7. お問い合わせ</h2>
    <p>個人情報の取り扱いに関するご質問や削除依頼は、お問い合わせページからご連絡ください。</p>
    <p>本人確認が必要な場合は、追加の確認をお願いすることがあります。</p>
