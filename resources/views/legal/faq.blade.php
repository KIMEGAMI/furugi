    <h2>プランについて</h2>

    <h3>Freeプランでは何ができますか？</h3>
    <p>商品登録、画像付きの商品管理、SOLD管理、基本ダッシュボードを利用できます。</p>
    <p>Freeプランは、まず操作感を試したい方向けです。商品登録数には制限があります。</p>

    <h3>Premiumプランでは何が増えますか？</h3>
    <p>商品登録数の上限拡張、CSV取込、CSV出力、売上分析、ジャンル別分析などを利用できます。</p>
    <p>出品数が増えてきた方、売上や利益を継続的に確認したい方に向いています。</p>

    <h3>料金はいくらですか？</h3>
    <p>Premiumプランは月額480円を想定しています。</p>
    <p>決済や請求管理は、外部決済サービスを通じて行います。実際の金額は決済画面をご確認ください。</p>

    <h2>商品登録について</h2>

    <h3>画像の容量制限はありますか？</h3>
    <p>1枚あたり2MBまでです。JPG、PNG、WEBPなど一般的な画像形式を想定しています。</p>
    <p>スマホPWAでは、商品登録画面からカメラを起動して、その場で撮影した画像を登録できます。</p>

    <h3>ユーザーを削除すると画像も削除されますか？</h3>
    <p>ユーザーを削除した場合、そのユーザーが登録していた商品画像も削除される設計です。</p>
    <p>誤って削除した場合に備え、必要な画像やデータは事前に控えを残してください。</p>

    <h3>CSVでまとめて登録できますか？</h3>
    <p>CSV取込はPremium向け機能です。</p>
    <p>複数の商品をまとめて登録したい場合や、外部で作成した一覧を取り込みたい場合に利用できます。</p>

    <h2>売上管理について</h2>

    <h3>SOLD管理はできますか？</h3>
    <p>販売済みの商品をSOLDとして管理できます。</p>
    <p>仕入れ価格、販売価格、販売手数料、送料を登録しておくことで、売上や利益の把握に役立ちます。</p>

    <h3>ジャンル別の分析はできますか？</h3>
    <p>Premiumでは、ジャンル別の売上傾向を確認できます。</p>
    <p>売れやすいカテゴリを把握し、次の仕入れ判断に活用できます。</p>

    <h2>アカウントと安全性について</h2>

    <h3>デモを見ることはできますか？</h3>
    <p>ログイン画面のデモボタンから、実際の画面を確認できます。</p>
    <p>本格的に利用する前に、商品登録や売上管理の流れを試せます。</p>

    <h3>メンテナンス中はどうなりますか？</h3>
    <p>メンテナンス中は、一般ユーザーの利用を一時停止します。</p>
    <p>管理者のみ管理画面へアクセスでき、メンテナンス状態の切り替えや確認を行えます。</p>
